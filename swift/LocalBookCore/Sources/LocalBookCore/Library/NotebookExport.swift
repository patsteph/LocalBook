import Foundation

/// A notebook written out for people: the old app's `_generate_markdown` shape (title, exported stamp, one heading per
/// source with its facts, the text in a fence, then the notes and the questions asked), and the same as a standalone
/// HTML page. Pure, so Swift Testing can hold the shape still while the Mac app only chooses where the file goes.
public enum NotebookExport {
    public struct Source: Sendable {
        public var name: String
        public var format: String
        public var chunks: Int
        public var characters: Int
        public var url: String?
        public var text: String?
        public init(name: String, format: String, chunks: Int, characters: Int, url: String? = nil, text: String? = nil) {
            self.name = name; self.format = format; self.chunks = chunks; self.characters = characters; self.url = url; self.text = text
        }
    }

    public struct Note: Sendable {
        public var title: String
        public var text: String
        public init(title: String, text: String) { self.title = title; self.text = text }
    }

    public struct Exchange: Sendable {
        public struct Citation: Sendable {
            public var number: Int
            public var filename: String
            public var snippet: String
            public init(number: Int, filename: String, snippet: String) { self.number = number; self.filename = filename; self.snippet = snippet }
        }
        public var question: String
        public var answer: String
        public var citations: [Citation]
        public init(question: String, answer: String, citations: [Citation] = []) { self.question = question; self.answer = answer; self.citations = citations }
    }

    public struct Notebook: Sendable {
        public var title: String
        public var description: String?
        public var sources: [Source]
        public var notes: [Note]
        public var exchanges: [Exchange]
        public init(title: String, description: String? = nil, sources: [Source] = [], notes: [Note] = [], exchanges: [Exchange] = []) {
            self.title = title; self.description = description; self.sources = sources; self.notes = notes; self.exchanges = exchanges
        }
    }

    /// The old app cut each source's text at this many characters in the export.
    public static let contentLimit = 5000

    public static func stamp(_ date: Date) -> String {
        let f = DateFormatter()
        f.locale = Locale(identifier: "en_US_POSIX")
        f.dateFormat = "yyyy-MM-dd HH:mm"
        return f.string(from: date)
    }

    public static func markdown(_ nb: Notebook, includeContent: Bool, date: Date = Date()) -> String {
        var lines: [String] = ["# \(nb.title)", ""]
        if let d = nb.description, !d.isEmpty { lines += ["_\(d)_", ""] }
        lines += ["Exported: \(stamp(date))", "", "## Sources", ""]
        if nb.sources.isEmpty {
            lines += ["_No sources in this notebook_", ""]
        }
        for (i, s) in nb.sources.enumerated() {
            lines.append("### \(i + 1). \(s.name)")
            lines.append("- **Format:** \(s.format.uppercased())")
            lines.append("- **Chunks:** \(s.chunks)")
            lines.append("- **Characters:** \(grouped(s.characters))")
            lines.append("- **Status:** completed")
            if let url = s.url, !url.isEmpty { lines.append("- **URL:** \(url)") }
            lines.append("")
            if includeContent, let text = s.text, !text.isEmpty {
                lines += ["#### Content", "```"]
                lines.append(String(text.prefix(contentLimit)))
                if text.count > contentLimit { lines.append("... (truncated)") }
                lines += ["```", ""]
            }
        }
        if !nb.notes.isEmpty {
            lines += ["## Notes", ""]
            for n in nb.notes {
                lines.append("### \(n.title)")
                lines.append("")
                lines.append(n.text)
                lines.append("")
            }
        }
        if !nb.exchanges.isEmpty {
            lines += ["## Q&A History", ""]
            for (i, e) in nb.exchanges.enumerated() {
                lines += ["### Q\(i + 1): \(e.question)", "", "**Answer:** \(e.answer)", ""]
                if !e.citations.isEmpty {
                    lines.append("**Citations:**")
                    for c in e.citations { lines.append("- [\(c.number)] \(c.filename): \(String(c.snippet.prefix(100)))...") }
                    lines.append("")
                }
            }
        }
        lines += ["---", "_Generated by LocalBook_"]
        return lines.joined(separator: "\n")
    }

    /// The same export as a page that opens in any browser and prints to PDF from there, as the old app's PDF did.
    public static func html(_ nb: Notebook, includeContent: Bool, date: Date = Date()) -> String {
        var out: [String] = []
        out.append("<!DOCTYPE html><html><head><meta charset=\"utf-8\"><title>\(escape(nb.title))</title>")
        out.append("<style>body{font-family:-apple-system,Helvetica,Arial,sans-serif;max-width:800px;margin:40px auto;padding:0 20px;line-height:1.5;color:#1d1d1f}")
        out.append("h1{border-bottom:1px solid #ddd;padding-bottom:8px}h3{margin-bottom:4px}pre{background:#f5f5f7;padding:12px;border-radius:8px;white-space:pre-wrap;word-break:break-word}")
        out.append("blockquote{border-left:3px solid #ccc;margin:0;padding-left:12px;color:#555}.meta{color:#6e6e73;font-size:.9em}footer{margin-top:40px;color:#6e6e73;font-size:.85em}</style></head><body>")
        out.append("<h1>\(escape(nb.title))</h1>")
        if let d = nb.description, !d.isEmpty { out.append("<p><em>\(escape(d))</em></p>") }
        out.append("<p class=\"meta\">Exported: \(stamp(date))</p>")
        out.append("<h2>Sources</h2>")
        if nb.sources.isEmpty { out.append("<p><em>No sources in this notebook</em></p>") }
        for (i, s) in nb.sources.enumerated() {
            out.append("<h3>\(i + 1). \(escape(s.name))</h3>")
            var facts = "<p class=\"meta\">\(escape(s.format.uppercased())) · \(s.chunks) chunks · \(grouped(s.characters)) characters"
            if let url = s.url, !url.isEmpty { facts += " · <a href=\"\(escape(url))\">\(escape(url))</a>" }
            out.append(facts + "</p>")
            if includeContent, let text = s.text, !text.isEmpty {
                var shown = String(text.prefix(contentLimit))
                if text.count > contentLimit { shown += "\n... (truncated)" }
                out.append("<pre>\(escape(shown))</pre>")
            }
        }
        if !nb.notes.isEmpty {
            out.append("<h2>Notes</h2>")
            for n in nb.notes { out.append("<h3>\(escape(n.title))</h3><pre>\(escape(n.text))</pre>") }
        }
        if !nb.exchanges.isEmpty {
            out.append("<h2>Q&amp;A History</h2>")
            for (i, e) in nb.exchanges.enumerated() {
                out.append("<h3>Q\(i + 1): \(escape(e.question))</h3><p>\(escape(e.answer).replacingOccurrences(of: "\n", with: "<br>"))</p>")
                if !e.citations.isEmpty {
                    out.append("<ul>")
                    for c in e.citations { out.append("<li>[\(c.number)] \(escape(c.filename)): \(escape(String(c.snippet.prefix(100))))...</li>") }
                    out.append("</ul>")
                }
            }
        }
        out.append("<footer>Generated by LocalBook</footer></body></html>")
        return out.joined(separator: "\n")
    }

    /// A file name the Finder accepts for `title`: slashes and colons become dashes, nothing is left empty.
    public static func fileName(_ title: String) -> String {
        var s = title.replacingOccurrences(of: "/", with: "-").replacingOccurrences(of: ":", with: "-")
        s = s.trimmingCharacters(in: .whitespacesAndNewlines)
        while s.hasPrefix(".") { s.removeFirst() }
        return s.isEmpty ? "Untitled" : String(s.prefix(120))
    }

    static func grouped(_ n: Int) -> String {
        let f = NumberFormatter()
        f.numberStyle = .decimal
        f.locale = Locale(identifier: "en_US_POSIX")
        f.groupingSeparator = ","
        f.usesGroupingSeparator = true
        return f.string(from: NSNumber(value: n)) ?? String(n)
    }

    static func escape(_ s: String) -> String {
        s.replacingOccurrences(of: "&", with: "&amp;").replacingOccurrences(of: "<", with: "&lt;")
            .replacingOccurrences(of: ">", with: "&gt;").replacingOccurrences(of: "\"", with: "&quot;")
    }
}
