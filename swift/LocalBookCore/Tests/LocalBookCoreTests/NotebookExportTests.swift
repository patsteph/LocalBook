import Foundation
import Testing
@testable import LocalBookCore

/// The notebook export keeps the old app's Markdown shape and makes a page that stands alone.
@Suite("Notebook export")
struct NotebookExportTests {
    static let when = Date(timeIntervalSince1970: 1_700_000_000)   // 2023-11-14 22:13 UTC

    static func sample() -> NotebookExport.Notebook {
        NotebookExport.Notebook(
            title: "Trip: Lisbon/2026", description: "Plans",
            sources: [
                .init(name: "guide.pdf", format: "pdf", chunks: 12, characters: 34567, text: "Page one.\nPage two."),
                .init(name: "Tram 28", format: "web", chunks: 3, characters: 900, url: "https://x.y/tram", text: String(repeating: "a", count: 5010)),
            ],
            notes: [.init(title: "Packing", text: "- [ ] charger")],
            exchanges: [.init(question: "When?", answer: "In May.", citations: [.init(number: 1, filename: "guide.pdf", snippet: "May is mild")])])
    }

    @Test("markdown has the old headings, facts, fenced content cut at the limit, notes and Q&A")
    func markdown() {
        let md = NotebookExport.markdown(Self.sample(), includeContent: true, date: Self.when)
        #expect(md.hasPrefix("# Trip: Lisbon/2026\n\n_Plans_\n\nExported: "))
        #expect(md.contains("## Sources\n\n### 1. guide.pdf\n- **Format:** PDF\n- **Chunks:** 12\n- **Characters:** 34,567\n- **Status:** completed\n\n#### Content\n```\nPage one.\nPage two.\n```"))
        #expect(md.contains("- **URL:** https://x.y/tram"))
        #expect(md.contains("... (truncated)"))
        #expect(md.contains("## Notes\n\n### Packing\n\n- [ ] charger"))
        #expect(md.contains("### Q1: When?\n\n**Answer:** In May.\n\n**Citations:**\n- [1] guide.pdf: May is mild..."))
        #expect(md.hasSuffix("---\n_Generated by LocalBook_"))
        let bare = NotebookExport.markdown(Self.sample(), includeContent: false, date: Self.when)
        #expect(!bare.contains("#### Content"))
        #expect(NotebookExport.markdown(NotebookExport.Notebook(title: "Empty"), includeContent: true).contains("_No sources in this notebook_"))
    }

    @Test("html escapes and carries the same parts")
    func html() {
        let page = NotebookExport.html(Self.sample(), includeContent: true, date: Self.when)
        #expect(page.hasPrefix("<!DOCTYPE html>"))
        #expect(page.contains("<title>Trip: Lisbon/2026</title>"))
        #expect(page.contains("<h3>1. guide.pdf</h3>"))
        #expect(page.contains("<pre>Page one.\nPage two.</pre>"))
        #expect(page.contains("<a href=\"https://x.y/tram\">"))
        #expect(page.contains("<h2>Q&amp;A History</h2>"))
        #expect(page.contains("[1] guide.pdf: May is mild..."))
        let sharp = NotebookExport.html(NotebookExport.Notebook(title: "<b>&"), includeContent: false)
        #expect(sharp.contains("<h1>&lt;b&gt;&amp;</h1>"))
    }

    @Test("file names drop what the Finder refuses")
    func names() {
        #expect(NotebookExport.fileName("Trip: Lisbon/2026") == "Trip- Lisbon-2026")
        #expect(NotebookExport.fileName("  ") == "Untitled")
        #expect(NotebookExport.fileName("..hidden") == "hidden")
    }
}
